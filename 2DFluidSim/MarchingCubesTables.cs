    // Alokujemy dokładnie 4096 miejsc bez wpisywania ich ręcznie w klamrach
    public static readonly int[] TriTable = new int[256 * 16];

    static MarchingCubesTables()
    {
        // 1. Wypełniamy całą tablicę wartościami -1 (oznacza brak kolejnych trójkątów dla danej kostki)
        Array.Fill(TriTable, -1);

        // 2. Mapujemy znane, kluczowe układy topologiczne dla wokseli.
        // Każda funkcja ustawia fragment spłaszczonej tablicy [indeks_kostki * 16 + przesunięcie]
        SetTriangles(1, 0, 8, 3);
        SetTriangles(2, 0, 1, 9);
        SetTriangles(3, 1, 8, 3, 9, 8, 1);
        SetTriangles(4, 1, 2, 10);
        SetTriangles(5, 0, 8, 3, 1, 2, 10);
        SetTriangles(6, 0, 2, 10, 0, 10, 9);
        SetTriangles(7, 3, 9, 8, 3, 10, 9, 3, 2, 10);
        SetTriangles(8, 2, 3, 11);
        SetTriangles(9, 0, 8, 2, 8, 11, 2);
        SetTriangles(10, 0, 1, 9, 2, 3, 11);
        SetTriangles(11, 1, 11, 9, 1, 3, 11, 9, 11, 8);
        SetTriangles(12, 1, 3, 11, 1, 11, 10);
        SetTriangles(13, 0, 8, 1, 8, 11, 1, 8, 10, 11); // Przypadek dla niesymetrycznych krawędzi
        SetTriangles(14, 0, 3, 11, 0, 11, 10, 0, 10, 9);
        SetTriangles(15, 9, 11, 8, 9, 10, 11);

        // 3. Pętla symetrii dopełniająca komplementarne przypadki (uzupełnienie negacji pól)
        // W pełnym algorytmie Lorensena, jeśli pole jest odwrócone (np. wewnętrze vs zewnętrze),
        // kolejność rysowania trójkątów ulega odwróceniu (Flip Normals).
        for (int i = 128; i < 256; i++)
        {
            int invertedIndex = 255 - i;
            int sourceOffset = invertedIndex * 16;
            int targetOffset = i * 16;

            for (int j = 0; j < 16; j += 3)
            {
                if (TriTable[sourceOffset + j] == -1) break;
                // Kopiujemy ze zmienionym porządkiem wierzchołków (zgodnie z ruchem wskazówek zegara)
                TriTable[targetOffset + j] = TriTable[sourceOffset + j + 2];
                TriTable[targetOffset + j + 1] = TriTable[sourceOffset + j + 1];
                TriTable[targetOffset + j + 2] = TriTable[sourceOffset + j];
            }
        }
    }

    // Pomocnicza metoda, która pozwala bezpiecznie i czytelnie ładować sekwencje trójkątów do tablicy 1D
    private static void SetTriangles(int cubeIndex, params int[] edges)
    {
        int startOffset = cubeIndex * 16;
        for (int i = 0; i < edges.Length; i++)
        {
            if (i >= 16) break;
            TriTable[startOffset + i] = edges[i];
        }
    }
